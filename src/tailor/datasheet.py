"""Dataset datasheet: one markdown document describing a delivery.

Bundles what a recipient needs to accept a dataset: what it contains, how the
acceptance suite judged it, where it came from (ledger lineage), and how much
usable footage it holds. Generated from meta-level reads plus one run of the
check suite — same cost class as check itself.
"""

from datetime import datetime
from pathlib import Path
from typing import Any

from tailor.ledger import read_ledger, render_ledger
from tailor.loader import load_snapshot
from tailor.model import CheckResult, Status


def _overview_table(info: dict, snap: Any) -> list[str]:
    episodes = len(snap.episodes or [])
    total_frames = info.get("total_frames") or 0
    fps = info.get("fps") or 0
    hours = total_frames / fps / 3600 if fps else 0.0
    rows = [
        "| field | value |",
        "| --- | --- |",
        f"| format version | {info.get('codebase_version', '?')} |",
        f"| robot type | {info.get('robot_type', '?')} |",
        f"| fps | {info.get('fps', '?')} |",
        f"| episodes | {episodes} |",
        f"| total frames | {total_frames} |",
        f"| total footage | {hours:.2f} h |",
        f"| tasks | {info.get('total_tasks', '?')} |",
    ]
    splits = info.get("splits")
    if splits:
        rows.append(f"| splits | {splits} |")
    return rows


def _features_table(info: dict) -> list[str]:
    features = info.get("features") or {}
    if not features:
        return ["_no features declared_"]
    rows = ["| feature | dtype | shape |", "| --- | --- | --- |"]
    for key, feat in features.items():
        rows.append(f"| {key} | {feat.get('dtype', '?')} | {feat.get('shape', '?')} |")
    return rows


def _acceptance_section(results: list[CheckResult]) -> list[str]:
    counts: dict[str, int] = {}
    for r in results:
        counts[r.status.value] = counts.get(r.status.value, 0) + 1
    summary = ", ".join(f"{n} {s}" for s, n in sorted(counts.items()))
    rows = [f"Verdict counts: {summary}", "", "| check | status | detail |", "| --- | --- | --- |"]
    for r in results:
        if r.status == Status.PASS:
            continue
        detail = (r.message or "").replace("|", "\\|")
        rows.append(f"| {r.name} | {r.status.value} | {detail[:120]} |")
    if all(r.status == Status.PASS for r in results):
        rows.append("| — | PASS | all checks passed |")
    return rows


def build_datasheet(root: Path, results: list[CheckResult]) -> str:
    """Markdown datasheet for one dataset, given its check results."""
    snap = load_snapshot(root)
    info = snap.info or {}
    lines = [
        f"# Datasheet: {root.name}",
        "",
        f"Generated by tailor at {datetime.now():%Y-%m-%d %H:%M}.",
        "",
        "## Overview",
        "",
        *_overview_table(info, snap),
        "",
        "## Features",
        "",
        *_features_table(info),
        "",
        "## Acceptance",
        "",
        *_acceptance_section(results),
        "",
        "## Lineage",
        "",
        render_ledger(read_ledger(root)),
        "",
    ]
    return "\n".join(lines)
